    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        // TODO add your handling code here:
        String user = txtUsuario.getText().trim();
        String clave = new String(txtClave.getPassword());

        if (user.isEmpty() || clave.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingresa usuario y contraseña.");
        return;    }

        String sql = "SELECT id, username, rol FROM usuario WHERE username = ? AND clave = ?";

        try (Connection cn = Conexion.conectar();
        PreparedStatement ps = cn.prepareStatement(sql)) {

        ps.setString(1, user);
        ps.setString(2, clave);
        ResultSet rs = ps.executeQuery();

        if (rs.next()) {
            Usuario u = new Usuario(rs.getInt("id"), rs.getString("username"), rs.getString("rol"));
            FrmMenu menu = new FrmMenu(u);
            menu.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Usuario o contraseña incorrectos.");
            txtClave.setText("");
            txtUsuario.requestFocus();       }
        } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());        }
    }//GEN-LAST:event_btnIngresarActionPerformed

